#!/usr/bin/env node
/* Per-piece link previews for a static site (docs/module-api.md section 5, "Embeds and link previews").
 *
 * Unfurl bots (Slack, Discord, Mastodon, X, Zulip) read <meta> tags and never run scripts, so a link to
 * index.html?v=<id> always unfurls with the site-wide card. This writes one stub page per catalog piece,
 * v/<id>.html, carrying that piece's OpenGraph and Twitter tags (title, hook, and og/<id>.png when that file
 * exists, else og/default.png), which sends a person straight on to ../?v=<id>, keeping any &p= state.
 * Per-state previews (one image per &p=) need a server; this does not try.
 *
 *   node scripts/gen-share-pages.mjs [--origin https://loci.example]
 *
 * --origin (or LOCI_ORIGIN) makes og:image and og:url absolute, which most unfurlers require. Without it the
 * stubs use relative paths, which are fine for local testing. Text only: posters are not rendered here. */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = process.argv.indexOf('--origin');
const ORIGIN = (arg > 0 ? process.argv[arg + 1] : process.env.LOCI_ORIGIN || '').replace(/\/+$/, '');

/* The catalog is a page script: run kit.js, manifest.js and catalog.js in one context and read VIZ. Nothing in
   them touches the DOM at load time (canvases are made only when a piece draws). */
const ctx = vm.createContext({ console });
ctx.globalThis = ctx;
for (const f of ['kit.js', 'manifest.js', 'catalog.js']) vm.runInContext(readFileSync(join(ROOT, f), 'utf8'), ctx, { filename: f });
const VIZ = vm.runInContext('VIZ', ctx);

const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const abs = p => (ORIGIN ? `${ORIGIN}/${p}` : `../${p}`);

function page(v) {
  const img = existsSync(join(ROOT, 'og', `${v.id}.png`)) ? `og/${v.id}.png` : 'og/default.png';
  const title = `${v.title} · Loci`, desc = v.hook, target = `../?v=${encodeURIComponent(v.id)}`;
  const alt = img === 'og/default.png' ? 'The Loci card: chords on a circle forming a cardioid.' : (v.alt || v.title);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<!-- Generated by scripts/gen-share-pages.mjs. Do not edit by hand. -->
<title>${esc(title)}</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="${esc(desc)}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Loci">
<meta property="og:title" content="${esc(v.title)}">
<meta property="og:description" content="${esc(desc)}">
${ORIGIN ? `<meta property="og:url" content="${esc(`${ORIGIN}/v/${v.id}.html`)}">\n` : ''}<meta property="og:image" content="${esc(abs(img))}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="${esc(alt)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(v.title)}">
<meta name="twitter:description" content="${esc(desc)}">
<meta name="twitter:image" content="${esc(abs(img))}">
<link rel="canonical" href="${esc(ORIGIN ? `${ORIGIN}/?v=${encodeURIComponent(v.id)}` : target)}">
<script>location.replace(${JSON.stringify(target)}+location.search.replace(/^\\?/,'&')+location.hash);</script>
<noscript><meta http-equiv="refresh" content="0; url=${esc(target)}"></noscript>
</head>
<body>
<p><a href="${esc(target)}">${esc(v.title)}</a>, by ${esc(v.author)}, on Loci.</p>
</body>
</html>
`;
}

const dir = join(ROOT, 'v');
mkdirSync(dir, { recursive: true });
const ids = new Set(VIZ.map(v => `${v.id}.html`));
for (const f of readdirSync(dir)) if (f.endsWith('.html') && !ids.has(f)) unlinkSync(join(dir, f)); // pieces that left the catalog
for (const v of VIZ) writeFileSync(join(dir, `${v.id}.html`), page(v));
console.log(`wrote ${VIZ.length} pages to v/${ORIGIN ? ` for ${ORIGIN}` : ' (relative image paths; pass --origin for unfurlers)'}`);
