#!/usr/bin/env node
/* Writes catalog.js from a checkout of the registry: node scripts/gen-catalog.mjs [<registry-checkout>]   (default ../registry)
 * scripts/catalog-extras.json lists the pieces the site carries, in feed order, with what a package does not hold:
 * the review lane, reviewers, review date and the sample like counts. Everything else comes from entries/<id>/. A
 * WebAssembly piece's files are copied to examples/<id>/, which the site serves. Then run gen-share-pages.mjs and
 * sync-registry-checker.sh (demo/github/README.md, "The site's catalog"). */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = process.argv[2] || join(ROOT, '..', 'registry');
const REPO = 'EigenReel/registry', BRANCH = 'main';
const extras = JSON.parse(readFileSync(join(ROOT, 'scripts/catalog-extras.json'), 'utf8'));
const sha = execFileSync('git', ['-C', REGISTRY, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();

const pieces = extras.map(({ id, ...extra }) => {
  const dir = join(REGISTRY, 'entries', id);
  if (!existsSync(join(dir, 'loci.json'))) throw new Error(`${id} is in catalog-extras.json but not in ${dir}`);
  const man = JSON.parse(readFileSync(join(dir, 'loci.json'), 'utf8')), md = readFileSync(join(dir, 'explanation.md'), 'utf8');
  const v = { id, title: man.title, ...(extra.lane ? { lane: extra.lane } : {}), hook: man.hook, author: man.author, license: man.license,
    repo: `github.com/${REPO}/tree/${BRANCH}/entries/${id}`, reviewed: extra.reviewed, ...(extra.reviewers ? { reviewers: extra.reviewers } : {}),
    likes: extra.likes, t0: man.t0, tags: man.tags, alt: man.alt, manifest: man };
  if (man.runtime === 'wasm') {
    const out = join(ROOT, 'examples', id), files = readdirSync(dir), source = files.find(f => /\.(c|cpp|rs|zig|wat)$/.test(f));
    mkdirSync(out, { recursive: true });
    for (const f of files) if (f !== 'LICENSE') copyFileSync(join(dir, f), join(out, f));
    return { ...v, entry: `examples/${id}/${man.entry}`, sourceUrl: `examples/${id}/${source}`, mdUrl: `examples/${id}/explanation.md`, md: '' };
  }
  if (man.targets) return { ...v, md, sources: Object.fromEntries(man.targets.filter(t => t.entry).map(t => [t.id, readFileSync(join(dir, t.entry), 'utf8')])) };
  return { ...v, md, source: readFileSync(join(dir, man.entry || 'index.js'), 'utf8') };
});

writeFileSync(join(ROOT, 'catalog.js'), `/* Generated by scripts/gen-catalog.mjs from ${REPO} at ${sha}. Do not edit: change the entry in the registry, or
   scripts/catalog-extras.json, and generate it again. reviewers: on Feed-lane pieces, the two people who checked the
   mathematics (docs/review-pipeline.md section 4). Sample data for the prototype, like the likes: no review has run. */
const VIZ = [
${pieces.map(p => JSON.stringify(p)).join(',\n')}
];
function moduleSource(v,tid){
  const t=v.manifest.targets?(tid&&targetById(v.manifest,tid))||runnableTargets(v.manifest)[0]:null;
  if((t?t.runtime:v.manifest.runtime)!=='js') return null;
  return v.sources?v.sources[t.id]??null:v.source; // one module per target (docs/module-api.md, "Targets")
}
VIZ.forEach(v=>validateManifest(v.manifest));
`);
console.log(`catalog.js: ${pieces.length} pieces from ${REPO} at ${sha}`);
