#!/usr/bin/env node
/* Writes catalog.js from the registry's entries (docs/submission-spec-slop.md):
 *   node scripts/gen-catalog.mjs [<registry-checkout>]        (default: demo/github/registry, the copy versioned here)
 * scripts/catalog-extras.json lists the pieces the site carries, in feed order, with what an entry does not hold:
 * the review lane, the reviewers, the review date, the sample like counts and the author's handle on the site.
 * Everything else is read from entries/<id>.js and entries/<id>.md with spec.js, as data: nothing here runs piece
 * code, and the site keeps using only this metadata (spec, section 1). A piece's .wasm is copied to wasm/<id>.wasm.
 * Then run gen-share-pages.mjs (demo/github/README.md, "The site's catalog"). */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, readdirSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = process.argv[2] || join(ROOT, 'demo/github/registry');
const REPO = 'EigenReel/registry', BRANCH = 'main';
const Spec = createRequire(import.meta.url)(join(ROOT, 'spec.js'));
const extras = JSON.parse(readFileSync(join(ROOT, 'scripts/catalog-extras.json'), 'utf8'));
let sha = 'local';
try { sha = execFileSync('git', ['-C', REGISTRY, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { /* not a checkout of its own */ }
let vocabulary = Spec.DEFAULT_TAGS;
if (existsSync(join(REGISTRY, 'tags.json'))) vocabulary = JSON.parse(readFileSync(join(REGISTRY, 'tags.json'), 'utf8'));

const wasmDir = join(ROOT, 'wasm');
mkdirSync(wasmDir, { recursive: true });
const problems = [];
const pieces = [];
for (const { id, ...extra } of extras) {
  const js = join(REGISTRY, 'entries', `${id}.js`), md = join(REGISTRY, 'entries', `${id}.md`), wasm = join(REGISTRY, 'entries', `${id}.wasm`);
  if (!existsSync(js)) throw new Error(`${id} is in catalog-extras.json but ${js} does not exist`);
  const source = readFileSync(js, 'utf8'), explanation = existsSync(md) ? readFileSync(md, 'utf8') : null;
  const r = Spec.read(source);
  if (!r.ok) throw new Error(`${id}: ${r.errors.map(e => `line ${e.line}: ${e.message}`).join('; ')}`);
  for (const p of Spec.validateMeta(r.meta, r.colors, { vocabulary })) problems.push(`${id}: ${p.field}: ${p.message}`);
  if (explanation) for (const p of Spec.explanationProblems(explanation, r.meta).errors) problems.push(`${id}.md line ${p.line}: ${p.message}`);
  else problems.push(`${id}: entries/${id}.md is missing`);
  const v = {
    id, title: r.meta.title, ...(extra.lane ? { lane: extra.lane } : {}), hook: r.meta.hook, alt: r.meta.alt,
    author: { name: r.meta.author.name, ...(extra.handle ? { handle: extra.handle } : {}) }, license: r.meta.license,
    repo: `github.com/${REPO}/tree/${BRANCH}/entries/${id}.js`, reviewed: extra.reviewed, ...(extra.reviewers ? { reviewers: extra.reviewers } : {}),
    likes: extra.likes, tags: r.meta.tags, colors: r.colors, meta: r.meta, source, md: explanation || '',
  };
  if (existsSync(wasm)) { copyFileSync(wasm, join(wasmDir, `${id}.wasm`)); v.wasm = `wasm/${id}.wasm`; }
  pieces.push(v);
}
for (const f of readdirSync(wasmDir)) if (!pieces.some(v => v.wasm === `wasm/${f}`)) unlinkSync(join(wasmDir, f));
if (problems.length) { console.error('catalog pieces that fail the gate:\n  ' + problems.join('\n  ')); process.exit(1); }

const head = `/* Generated by scripts/gen-catalog.mjs from ${REPO} at ${sha}. Do not edit: change the entry in the registry, or
   scripts/catalog-extras.json, and generate it again. Each piece carries its source and explanation as written, and the
   metadata spec.js read from the source (docs/submission-spec-slop.md). reviewers: on Feed-lane pieces, the two people
   who checked the mathematics. Sample data for the prototype, like the likes: no review has run. */
const VIZ = [
`;
writeFileSync(join(ROOT, 'catalog.js'), head + pieces.map(v => JSON.stringify(v)).join(',\n') + '\n];\n');
console.log(`catalog.js: ${pieces.length} pieces from ${REGISTRY} (${sha})`);
