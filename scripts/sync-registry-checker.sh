#!/bin/sh
# Copies the Loci gate into the registry template, so the registry's "check" workflow runs the same static checks
# as the Submit page (demo/github/README.md, "Keeping the checker in sync"). Run it from anywhere after changing
# checks.js, manifest.js, tex.js, kit.js, catalog.js, bounties.js or demo/server/guard.js, then commit the result
# here and copy demo/github/registry/.loci/ into the registry repository as well. catalog.js is generated from the
# registry (scripts/gen-catalog.mjs), so run that first.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEST="$ROOT/demo/github/registry/.loci"

cp "$ROOT/demo/server/guard.js" "$DEST/guard.js"
for f in checks.js manifest.js tex.js kit.js; do cp "$ROOT/$f" "$DEST/$f"; done

# catalog-index.json: what the gate reads from the catalog and the Wanted list, as data (the registry has no page).
#   pieces: [{id, title, tags, manifest, sources: {target: module source | null}}]  (tag vocabulary, "after" ids, duplicates)
#   wanted: [{id, status, title, answer?}]                                          (the bounty check)
ROOT="$ROOT" node --input-type=module -e '
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import vm from "node:vm";
const ROOT = process.env.ROOT;
const ctx = vm.createContext({ console }); ctx.globalThis = ctx;
for (const f of ["kit.js", "manifest.js", "catalog.js", "bounties.js"]) vm.runInContext(readFileSync(join(ROOT, f), "utf8"), ctx, { filename: f });
const { VIZ, WANTED, manifestJSON, runnableTargets, moduleSource } = vm.runInContext("({ VIZ, WANTED, manifestJSON, runnableTargets, moduleSource })", ctx);
const pieces = VIZ.map(v => ({ id: v.id, title: v.title, tags: v.tags, manifest: JSON.parse(manifestJSON(v.manifest)),
  sources: Object.fromEntries(runnableTargets(v.manifest).map(t => [t.id, t.runtime === "js" ? moduleSource(v, t.id) : null])) }));
const wanted = WANTED.map(c => ({ id: c.id, status: c.status, title: c.title, ...(c.answer ? { answer: c.answer } : {}) }));
writeFileSync(join(ROOT, "demo/github/registry/.loci/catalog-index.json"), JSON.stringify({ note: "Generated by scripts/sync-registry-checker.sh. Do not edit by hand.", pieces, wanted }) + "\n");
console.log(`catalog-index.json: ${pieces.length} pieces, ${wanted.length} Wanted requests`);
'
echo "Copied guard.js, checks.js, manifest.js, tex.js and kit.js into $DEST"
